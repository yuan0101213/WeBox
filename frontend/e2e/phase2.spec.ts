import { test, expect } from '@playwright/test';

test('preferences, allergen confirmation, five-meal limit and existing order', async ({ page }) => {
  const credentials = { email: `prefs-${Date.now()}@example.test`, password: 'TestPass123' };
  await page.request.post('/api/auth/register', { data: credentials });
  await page.goto('/login');
  await page.getByLabel('Work email').fill(credentials.email);
  await page.getByLabel('Password', { exact: true }).fill(credentials.password);
  await page.getByRole('button', { name: 'Log in', exact: true }).click();
  await page.getByRole('link', { name: 'Preferences', exact: true }).click();
  await page.getByLabel('Allergens', { exact: true }).click();
  await page.locator('.ant-select-dropdown:visible .ant-select-item-option-content').filter({ hasText: /^Peanuts$/ }).click();
  await page.getByRole('heading', { name: 'Dietary preferences' }).click();
  await page.getByLabel('Favorite cuisines').click();
  await page.locator('.ant-select-dropdown:visible .ant-select-item-option-content').filter({ hasText: /^Japanese$/ }).click();
  await page.getByRole('heading', { name: 'Dietary preferences' }).click();
  await page.getByLabel('Maximum budget (¥)').fill('20');
  await page.getByRole('button', { name: 'Save preferences' }).click();
  await expect(page.getByText('Preferences saved.')).toBeVisible();
  await page.reload();
  await expect(page.locator('.ant-select-selection-item').filter({ hasText: 'Peanuts' })).toBeVisible();
  await page.getByRole('link', { name: 'Menu', exact: true }).click();
  await expect(page.locator('.dish-card')).toHaveCount(9);
  await expect(page.locator('.dish-thumb')).toHaveCount(3);
  await page.getByRole('switch').click();
  await expect(page.locator('.dish-card').first()).toContainText('Salmon Sashimi Set');
  const chicken = page.locator('.dish-card').filter({ hasText: 'Kung Pao Chicken' });
  await chicken.getByRole('button', { name: 'Add to cart' }).click();
  await expect(page.getByText(/This dish contains an allergen you flagged/)).toBeVisible();
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  await page.getByRole('button', { name: 'Cart', exact: true }).click();
  await expect(page.getByText('Your cart is empty')).toBeVisible();
  await page.getByRole('button', { name: 'Close', exact: true }).click();
  for (let i = 0; i < 5; i++) {
    await chicken.getByRole('button', { name: 'Add to cart' }).click();
    await page.getByRole('button', { name: 'Add anyway', exact: true }).click();
  }
  await expect(chicken.getByRole('button', { name: 'Add to cart' })).toBeDisabled();
  await expect(page.getByText('Maximum 5 meals per order. Remove a meal to add another.')).toBeVisible();
  await page.getByRole('button', { name: 'Cart', exact: true }).click();
  await expect(page.getByRole('spinbutton')).toHaveValue('5');
  await page.getByRole('button', { name: 'Checkout', exact: true }).click();
  await expect(page.getByText(/Your total is above your budget/)).toBeVisible();
  const token = await page.evaluate(() => sessionStorage.getItem('webox.token'));
  const date = await page.getByLabel('Delivery date').inputValue();
  const meal = (await page.locator('.ant-select-selection-item').first().textContent())!;
  const response = await page.request.post('/api/orders', { headers: { Authorization: `Bearer ${token}` }, data: { requestId: crypto.randomUUID(), deliveryDate: date, mealPeriod: meal, address: 'Preference test office', items: [{ dishId: 1, quantity: 1, selectedOptions: [] }] } });
  expect(response.status()).toBe(200);
  await page.reload();
  await expect(page.getByRole('button', { name: 'View Existing Order' })).toBeVisible();
  await page.getByRole('button', { name: 'View Existing Order' }).click();
  await page.getByRole('button', { name: 'Cancel order', exact: true }).click();
  await page.getByRole('button', { name: 'Cancel order', exact: true }).last().click();
  await expect(page.getByText('Cancelled', { exact: true })).toBeVisible();
  await page.goto('/console');
  await expect(page).toHaveURL(/\/menu/);
});

test('administrator uses simple Console CRUD and daily menu', async ({ page }) => {
  await page.goto('/login');
  await page.getByLabel('Work email').fill('superadmin@webox.test');
  await page.getByLabel('Password', { exact: true }).fill('WeBoxAdmin123');
  await page.getByRole('button', { name: 'Log in', exact: true }).click();
  await expect(page).toHaveURL(/\/console/);
  const name = `Browser Salad ${Date.now()}`;
  await page.getByRole('button', { name: 'Add dish' }).click();
  await page.getByLabel('Name', { exact: true }).fill(name);
  await page.getByLabel('Description', { exact: true }).fill('Fresh greens for a workday lunch');
  await page.getByLabel('Price (CNY)').fill('18.50');
  await page.getByRole('button', { name: 'OK', exact: true }).click();
  await expect(page.getByText('Dish saved.')).toBeVisible();
  const row = page.getByRole('row').filter({ hasText: name });
  await expect(row).toContainText('¥18.50');
  await row.getByRole('button', { name: 'Edit', exact: true }).click();
  await page.getByLabel('Price (CNY)').fill('19.50');
  await page.getByRole('button', { name: 'OK', exact: true }).click();
  await expect(row).toContainText('¥19.50');
  await row.getByRole('button', { name: 'Take off sale' }).click();
  await expect(row.getByText('Inactive', { exact: true })).toBeVisible();
  await row.getByRole('button', { name: 'Put on sale' }).click();
  await page.getByRole('tab', { name: 'Daily menu', exact: true }).click();
  const future = new Date(); future.setDate(future.getDate() + 31);
  await page.getByLabel('Daily menu date').fill(future.toISOString().slice(0, 10));
  await expect(page.getByRole('button', { name: 'Save daily menu' })).toBeEnabled();
  const menuRow = page.getByRole('row').filter({ hasText: name });
  await menuRow.getByRole('checkbox').check();
  await page.getByRole('spinbutton', { name: `Supply quantity for ${name}` }).fill('25');
  await page.getByRole('button', { name: 'Save daily menu' }).click();
  await expect(page.getByText('Daily menu saved.')).toBeVisible();
  await page.screenshot({ path: '../docs/screenshots/console-daily-menu.png', fullPage: true });
  await menuRow.getByRole('checkbox').uncheck();
  await page.getByRole('button', { name: 'Save daily menu' }).click();
  await page.getByRole('tab', { name: 'Dishes', exact: true }).click();
  await page.getByRole('row').filter({ hasText: name }).getByRole('button', { name: 'Take off sale' }).click();
});

test('failed preferences load blocks add until retry succeeds', async ({ page }) => {
  const credentials = { email: `retry-${Date.now()}@example.test`, password: 'TestPass123' };
  await page.request.post('/api/auth/register', { data: credentials });
  let fail = true;
  await page.route('**/api/preferences', route => fail ? route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ message: 'Preferences unavailable.' }) }) : route.continue());
  await page.goto('/login');
  await page.getByLabel('Work email').fill(credentials.email);
  await page.getByLabel('Password', { exact: true }).fill(credentials.password);
  await page.getByRole('button', { name: 'Log in', exact: true }).click();
  await expect(page.getByText('Your preferences could not be loaded. Retry before adding a meal.')).toBeVisible();
  const add = page.locator('.dish-card').filter({ hasText: 'Kung Pao Chicken' }).getByRole('button', { name: 'Add to cart' });
  await expect(add).toBeDisabled();
  fail = false;
  await page.getByRole('button', { name: 'Retry', exact: true }).click();
  await expect(add).toBeEnabled();
});
