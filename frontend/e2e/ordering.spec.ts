import { test, expect } from '@playwright/test';

test('register, customize, persist cart, order and cancel on desktop and mobile', async ({ page }) => {
  const email = `browser-${Date.now()}@example.test`;
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/register');
  await page.getByLabel('Work email').fill(email);
  await page.getByLabel('Password', { exact: true }).fill('TestPass123');
  await page.getByRole('button', { name: 'Create account', exact: true }).click();
  await expect(page).toHaveURL(/\/login/);
  await page.getByLabel('Work email').fill(email);
  await page.getByLabel('Password', { exact: true }).fill('TestPass123');
  await page.getByRole('button', { name: 'Log in', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Daily menu' })).toBeVisible();
  await expect(page.locator('.dish-card')).toHaveCount(9);
  await expect(page.locator('.ant-spin-spinning')).toHaveCount(0);
  await expect(page.locator('.ant-spin-blur')).toHaveCount(0);
  await expect(page.locator('.ant-message-notice')).toHaveCount(0);
  await page.screenshot({ path: '../docs/screenshots/menu-desktop.png', fullPage: true });
  await page.getByRole('searchbox', { name: 'Search dishes' }).fill('pasta');
  await expect(page.locator('.dish-card')).toHaveCount(1);
  await expect(page.locator('.dish-card')).toContainText('Tomato Pasta');
  await page.getByRole('searchbox', { name: 'Search dishes' }).fill('');
  await expect(page.locator('.dish-card')).toHaveCount(9);
  await page.locator('.dish-card').filter({ hasText: 'Classic Beef Burger' }).getByRole('button', { name: 'Customize' }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByRole('button', { name: /Add to cart/ }).click();
  await expect(dialog.getByText('Choose 1 option(s) for Bun.')).toBeVisible();
  await dialog.getByRole('combobox', { name: 'Bun', exact: true }).click();
  await page.locator('.ant-select-dropdown:visible').getByText('Whole Wheat', { exact: true }).click();
  await dialog.getByRole('combobox', { name: 'Sauce', exact: true }).click();
  await page.locator('.ant-select-dropdown:visible').getByText('Mustard', { exact: true }).click();
  await dialog.getByRole('checkbox', { name: /Cheese/ }).check();
  await dialog.getByRole('button', { name: /Add to cart.*41.00/ }).click();
  await page.getByRole('button', { name: 'Cart', exact: true }).click();
  await page.getByRole('spinbutton').fill('2');
  await page.getByRole('spinbutton').press('Tab');
  await expect(page.getByText('Total ¥82.00')).toBeVisible();
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Daily menu' })).toBeVisible();
  await page.getByRole('button', { name: 'Cart', exact: true }).click();
  await expect(page.getByRole('spinbutton')).toHaveValue('2');
  await expect(page.getByText('Cheese · Whole Wheat · Mustard')).toBeVisible();
  await page.screenshot({ path: '../docs/screenshots/cart.png', fullPage: true });
  await page.getByRole('button', { name: 'Checkout', exact: true }).click();
  await page.locator('#address').fill('Building A, Floor 3, Room 301');
  await page.getByRole('button', { name: /Place order.*82.00/ }).click();
  await expect(page.getByText('Your order has been placed!')).toBeVisible();
  await expect(page.getByText('Cheese · Whole Wheat · Mustard')).toBeVisible();
  await page.screenshot({ path: '../docs/screenshots/order-success.png', fullPage: true });
  await page.getByRole('button', { name: 'Cancel order', exact: true }).click();
  await page.getByRole('button', { name: 'Cancel order', exact: true }).last().click();
  await expect(page.getByText('Cancelled', { exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Menu', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.locator('.dish-card')).toHaveCount(9);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await page.screenshot({ path: '../docs/screenshots/menu-mobile.png', fullPage: true });
  await page.getByRole('button', { name: 'Log out' }).click();
  await expect(page).toHaveURL(/\/login/);
  expect(errors).toEqual([]);
});
